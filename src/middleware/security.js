/**
 * Baseline security headers for the JSON API.
 *
 * The API is consumed cross-origin by the Next.js frontend, so this middleware
 * deliberately avoids a restrictive Content-Security-Policy (which belongs on
 * the frontend host) and focuses on headers that are safe for API responses.
 */
export function securityHeaders(_req, res, next) {
  res.setHeader("X-Content-Type-Options", "nosniff");
  res.setHeader("X-Frame-Options", "DENY");
  res.setHeader("Referrer-Policy", "strict-origin-when-cross-origin");
  res.setHeader(
    "Permissions-Policy",
    "camera=(), microphone=(), geolocation=(), payment=()"
  );

  if (process.env.NODE_ENV === "production") {
    res.setHeader(
      "Strict-Transport-Security",
      "max-age=31536000; includeSubDomains"
    );
  }

  next();
}
